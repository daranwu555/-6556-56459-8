const rnd = (n) => Math.floor(Math.random() * n);
const pick = (arr) => arr[rnd(arr.length)];
function shuffle(a) {
  a = a.slice();
  for (let i = a.length - 1; i > 0; i--) { const j = rnd(i + 1); [a[i], a[j]] = [a[j], a[i]]; }
  return a;
}
function numOptions(correct, spread, fmt = (x) => String(x)) {
  const set = new Set([correct]);
  let guard = 0;
  while (set.size < 4 && guard++ < 50) {
    const d = (rnd(4) + 1) * spread * (rnd(2) ? 1 : -1);
    if (correct + d > 0) set.add(correct + d);
  }
  while (set.size < 4) set.add(correct + set.size * spread);
  const wrong = [...set].filter((x) => x !== correct).map(fmt);
  return [fmt(correct), ...wrong];
}

