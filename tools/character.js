const LA = (m, c, prof, t = {}, o = matte, seg = 24) => m.add(lathe(prof, seg), m.mat(c, o), t);
const SP = (m, c, rx, ry, rz, x, y, z, o = matte, rot) => m.add(sphere(1, 20, 14), m.mat(c, o), { p: [x, y, z], s: [rx, ry, rz], r: rot });
